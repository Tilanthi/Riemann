from mpmath import mp
mp.dps = 30

def th3(y):
    """theta_3(0, exp(-pi*y)) for y>0, via the modular transform when y<1."""
    y = mp.mpf(y)
    if y >= 1:
        return mp.jtheta(3, 0, mp.e**(-mp.pi*y))
    return mp.jtheta(3, 0, mp.e**(-mp.pi/y)) / mp.sqrt(y)

def bracket(t, D):
    """theta3(e^{-pi t D}) theta3(e^{-pi t/D}) - 1/t, computed stably."""
    a, b = t*D, t/D
    if a < 1 and b < 1:                       # both transformed -> product = (1/t)*A*B
        A = mp.jtheta(3, 0, mp.e**(-mp.pi/a))
        B = mp.jtheta(3, 0, mp.e**(-mp.pi/b))
        return (A*B - 1)/t
    return th3(a)*th3(b) - 1/t

def G(ry, D):
    ry = mp.mpf(ry); D = mp.mpf(D)
    f = lambda t: mp.cos(ry*mp.log(t))*bracket(t, D)/mp.sqrt(t)
    I = mp.quad(f, [mp.mpf('1e-8'), mp.mpf('1e-3'), mp.mpf('0.01'), mp.mpf('0.1'), mp.mpf('0.5'), 1])
    return -2/(1+4*ry**2) + I

